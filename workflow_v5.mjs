import assert from 'node:assert/strict';
import {checkBasicNest,checkMilestone,applyMilestone,canSubmitType,canSeeProtected,canEditPublished} from '../assets/workflow.js';
import {translate} from '../assets/i18n.js';
import {createQrSvg} from '../assets/qr.js';
const nest={id:'PM-2026-100',season:2026,date_relocated:'2026-10-30',egg_count:107,species:'Green turtle',status:'incubating',updated_at:'2026-11-01T00:00:00Z'};
assert.equal(checkBasicNest(nest).id,nest.id);
assert.throws(()=>checkBasicNest({...nest,season:2025}),/Season/);
assert.equal(canSubmitType('warden','new_nest'),true);
assert.equal(canSubmitType('warden','milestone'),true);
assert.equal(canSubmitType('warden','correction'),false);
assert.equal(canSeeProtected('warden'),false);
assert.equal(canEditPublished('warden'),false);
assert.equal(canSeeProtected('admin'),true);
const s={payload:{status:'emerged',emergence_date:'2026-11-28',released_hatchlings:73},research_payload:{healthy_hatchlings:71,deformed_hatchlings:2}};
assert.deepEqual(checkMilestone(nest,s.payload,s.research_payload).publicDelta,s.payload);
assert.equal(applyMilestone(nest,{nest_code:'staff-hidden'},s).privateRecord.nest_code,'staff-hidden');
assert.equal(applyMilestone(nest,{},s).publicRecord.egg_count,107);
assert.throws(()=>checkMilestone(nest,{egg_count:500}),/cannot change/);
assert.throws(()=>checkMilestone(nest,{status:'excavated'}),/excavation date/i);
assert.throws(()=>checkMilestone(nest,{status:'emerged',released_hatchlings:10},{healthy_hatchlings:9,deformed_hatchlings:0}),/Release total/);
assert.throws(()=>checkMilestone({...nest,status:'excavated'},{status:'incubating'}),/cannot revert/);
assert.equal(translate('ms','incubating'),'Dalam pengeraman');
const svg=createQrSvg('https://example.org/portal/?nest=PM-2026-100');
assert.match(svg,/<svg /);assert.match(svg,/QR code/);assert.ok((svg.match(/<rect /g)||[]).length>20);
console.log('V5 workflow role gates, milestone integrity, Malay text and local QR generator: PASS');
